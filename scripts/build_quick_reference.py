"""Build QUICK-REFERENCE.md from the Common tasks table in each chapter. Edit the chapter, not the output.

    python3 scripts/build_quick_reference.py           # write QUICK-REFERENCE.md
    python3 scripts/build_quick_reference.py --check   # exit 1 if the file is out of date
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = """# Quick reference

A field manual for the book: every common task, with its command, in one place. It is built from the Common tasks table
at the end of each chapter, so it never disagrees with the chapter. Do not edit this file; edit the chapter and rebuild with
`python3 scripts/build_quick_reference.py`.

Commands assume the folder named above each table. Replace `<folder>` with a practice folder until you trust a run.

## Rules that apply everywhere

- Read the plan before you approve it. Apply only what you read.
- Back up before the first real run. Undo is not a backup.
- Real files never go in the repository. The commit guard refuses them.
- `release` and `adopt` are yours to run, never an agent's.
- A scanner that says "unknown" or "did not run" has told you nothing about safety.

"""


def chapter_files() -> list[Path]:
    """Chapter order: by chapter folder, the chapter's own file first, then its sub-chapters."""
    found = list((ROOT / "chapters").rglob("README.md")) + list((ROOT / "chapters").rglob("setup.md"))
    return sorted(found, key=lambda p: (p.relative_to(ROOT / "chapters").parts[0], len(p.relative_to(ROOT / "chapters").parts),
                                        p.relative_to(ROOT / "chapters").parts[1:]))


def title_of(text: str) -> str:
    match = re.search(r"^#\s+(.+)$", text, re.M)
    return match.group(1).strip() if match else "Untitled"


def common_tasks(text: str) -> str | None:
    match = re.search(r"^## Common tasks\n(.*?)(?=^## |\Z)", text, re.M | re.S)
    return match.group(1).strip() if match else None


def build() -> str:
    parts = [HEADER]
    for path in chapter_files():
        text = path.read_text()
        section = common_tasks(text)
        if not section:
            continue
        rel = path.relative_to(ROOT)
        parts.append(f"## [{title_of(text)}]({rel})\n\n{section}\n")
    return "\n".join(parts).rstrip() + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(usage=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    out = ROOT / "QUICK-REFERENCE.md"
    text = build()
    if args.check:
        sys.exit(0 if out.exists() and out.read_text() == text else 1)
    out.write_text(text)
    print(f"Wrote {out.name}: {text.count('## [')} chapters.")


if __name__ == "__main__":
    main()
